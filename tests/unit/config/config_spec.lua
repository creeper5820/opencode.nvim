local test = require("tests.support.test")

local function fresh()
  test.reload()
  return require("opencode")
end

test.describe("config", function()
  test.it("provides defaults without setup", function()
    local opencode = fresh()
    local config = opencode.get_config()
    test.equal("http://127.0.0.1:4096", config.server.url)
    test.deep_equal({}, config.server.headers)
    test.equal(nil, config.project.root)
    test.equal(48, config.sidebar.width)
    test.equal(8, config.sidebar.input_height)
    test.equal("<leader>oo", config.keymaps.toggle)
    test.equal("<leader>os", config.keymaps.send_selection)
    test.equal("<leader>oq", config.keymaps.question_selection)
    test.equal("<C-s>", config.keymaps.submit)
  end)

  test.it("allows setup() without options", function()
    local opencode = fresh()
    local config = opencode.setup()
    test.equal("http://127.0.0.1:4096", config.server.url)
    test.equal(48, config.sidebar.width)
    test.equal("<leader>oo", config.keymaps.toggle)
  end)

  test.it("merges partial overrides and keeps other defaults", function()
    local opencode = fresh()
    local config = opencode.setup({
      server = { url = "http://127.0.0.1:5000" },
      sidebar = { width = 60 },
      keymaps = { toggle = "<leader>ox" },
    })
    test.equal("http://127.0.0.1:5000", config.server.url)
    test.equal(60, config.sidebar.width)
    test.equal(8, config.sidebar.input_height)
    test.equal("<leader>ox", config.keymaps.toggle)
    test.equal("<leader>os", config.keymaps.send_selection)
  end)

  test.it("treats empty override tables as partial configuration", function()
    local opencode = fresh()
    local config = opencode.setup({ server = {}, project = {}, sidebar = {}, keymaps = {} })
    test.equal("http://127.0.0.1:4096", config.server.url)
    test.equal(48, config.sidebar.width)
    test.equal(8, config.sidebar.input_height)
    test.equal("<leader>oo", config.keymaps.toggle)
    test.equal("<C-s>", config.keymaps.submit)
  end)

  test.it("allows false to disable a keymap without re-applying defaults", function()
    local opencode = fresh()
    opencode.setup({ keymaps = { toggle = false, submit = false } })
    local config = opencode.get_config()
    test.equal(false, config.keymaps.toggle)
    test.equal(false, config.keymaps.submit)
    test.equal("<leader>os", config.keymaps.send_selection)
  end)

  test.it("inherits defaults for omitted or nil keymaps", function()
    local opencode = fresh()
    opencode.setup({ keymaps = { toggle = nil, send_selection = "<leader>ox" } })
    local config = opencode.get_config()
    test.equal("<leader>oo", config.keymaps.toggle)
    test.equal("<leader>ox", config.keymaps.send_selection)
    test.equal("<leader>oq", config.keymaps.question_selection)
    test.equal("<C-s>", config.keymaps.submit)
  end)

  test.it("is repeatable and replaces prior setup values", function()
    local opencode = fresh()
    opencode.setup({ sidebar = { width = 50 } })
    opencode.setup({ sidebar = { width = 70 } })
    local config = opencode.get_config()
    test.equal(70, config.sidebar.width)
    test.equal(8, config.sidebar.input_height)
  end)

  test.it("does not mutate defaults or the caller's options", function()
    local opencode = fresh()
    local opts = {
      server = { headers = { ["x-test"] = "yes" } },
      sidebar = { width = 50 },
    }
    opencode.setup(opts)
    opts.server.headers["x-test"] = "changed"
    opts.sidebar.width = 99
    local config = opencode.get_config()
    test.equal("yes", config.server.headers["x-test"])
    test.equal(50, config.sidebar.width)

    local defaults = require("opencode.config").defaults
    test.deep_equal({}, defaults.server.headers)
    opencode.setup({ sidebar = { width = 10 } })
    test.equal(48, defaults.sidebar.width)
  end)

  test.it("keeps the previous configuration when a later setup is invalid", function()
    local opencode = fresh()
    opencode.setup({ sidebar = { width = 50 } })
    local ok = pcall(opencode.setup, { sidebar = { width = 0 } })
    test.falsy(ok, "invalid setup must raise")
    test.equal(50, opencode.get_config().sidebar.width)
  end)

  test.it("accepts http URLs with optional ports, paths and IPv6 hosts", function()
    local opencode = fresh()
    for _, url in ipairs({
      "http://127.0.0.1:4096",
      "http://localhost:4096/",
      "http://127.0.0.1:4096/api",
      "http://[::1]:4096",
      "http://[::1]",
      "HTTP://127.0.0.1:4096",
    }) do
      local config = opencode.setup({ server = { url = url } })
      test.equal(url, config.server.url)
    end
  end)

  test.it("rejects malformed server URLs with a clear error", function()
    local opencode = fresh()
    test.error_matches("must be an absolute http:// URL", function()
      opencode.setup({ server = { url = "127.0.0.1:4096" } })
    end)
    test.error_matches("not supported yet", function()
      opencode.setup({ server = { url = "https://127.0.0.1:4096" } })
    end)
    test.error_matches("scheme %\"ftp%\" is not supported", function()
      opencode.setup({ server = { url = "ftp://127.0.0.1:4096" } })
    end)
    test.error_matches("invalid port", function()
      opencode.setup({ server = { url = "http://127.0.0.1:99999" } })
    end)
    test.error_matches("invalid port", function()
      opencode.setup({ server = { url = "http://127.0.0.1:abc" } })
    end)
    test.error_matches("must not contain whitespace", function()
      opencode.setup({ server = { url = "http://127.0.0.1:4096 nope" } })
    end)
    test.error_matches("non%-empty string", function()
      opencode.setup({ server = { url = "" } })
    end)
  end)

  test.it("rejects invalid headers", function()
    local opencode = fresh()
    test.error_matches("headers must be a table", function()
      opencode.setup({ server = { headers = "x" } })
    end)
    test.error_matches("must be a string", function()
      opencode.setup({ server = { headers = { authorization = 1 } } })
    end)
    test.error_matches("must not contain CR or LF", function()
      opencode.setup({ server = { headers = { ["x-test"] = "ok\r\ninjected: yes" } } })
    end)
    test.error_matches("must not contain CR or LF", function()
      opencode.setup({ server = { headers = { ["bad\nname"] = "value" } } })
    end)
  end)

  test.it("rejects invalid sidebar sizes", function()
    local opencode = fresh()
    test.error_matches("sidebar.width must be between", function()
      opencode.setup({ sidebar = { width = 0 } })
    end)
    test.error_matches("sidebar.width must be an integer", function()
      opencode.setup({ sidebar = { width = 1.5 } })
    end)
    test.error_matches("sidebar.input_height must be an integer", function()
      opencode.setup({ sidebar = { input_height = "8" } })
    end)
  end)

  test.it("rejects invalid keymap types", function()
    local opencode = fresh()
    test.error_matches("keymaps.toggle must be a non%-empty string or false", function()
      opencode.setup({ keymaps = { toggle = true } })
    end)
    test.error_matches("keymaps.submit must be a non%-empty string or false", function()
      opencode.setup({ keymaps = { submit = "" } })
    end)
    test.error_matches("keymaps.toggle must be a non%-empty string or false", function()
      opencode.setup({ keymaps = { toggle = 42 } })
    end)
  end)

  test.it("rejects invalid project.root", function()
    local opencode = fresh()
    test.error_matches("project.root", function()
      opencode.setup({ project = { root = "" } })
    end)
    test.error_matches("project.root", function()
      opencode.setup({ project = { root = 42 } })
    end)
  end)

  test.it("rejects non-table setup input", function()
    local opencode = fresh()
    test.error_matches("expects a table", function()
      opencode.setup("nope")
    end)
  end)
end)
