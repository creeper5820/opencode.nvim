local test = require("tests.support.test")

local function fresh()
  pcall(function()
    local opencode = require("opencode")
    if type(opencode.stop) == "function" then
      pcall(opencode.stop)
    end
  end)
  test.reload()
  return require("opencode")
end

test.describe("config", function()
  test.it("provides the terminal-first defaults without setup", function()
    local opencode = fresh()
    local config = opencode.get_config()
    test.equal("opencode", config.cmd)
    test.deep_equal({}, config.args)
    test.equal(nil, config.project.root)
    test.equal(false, config.session.continue)
    test.equal("right", config.window.layout)
    test.equal(80, config.window.size)
    test.equal("<leader>oo", config.keymaps.toggle)
    test.equal("<leader>os", config.keymaps.send_selection)
    test.equal("<leader>oq", config.keymaps.question_selection)
    test.equal(true, config.paste.bracketed)
    test.equal(nil, config.focus)
    test.equal(nil, config.keybindings)
    test.equal(nil, config.input)
  end)

  test.it("allows setup() with no options", function()
    local opencode = fresh()
    local config = opencode.setup()
    test.equal("opencode", config.cmd)
    test.equal("<leader>os", config.keymaps.send_selection)
    pcall(opencode.stop)
  end)

  test.it("merges partial overrides and replaces lists", function()
    local opencode = fresh()
    local config = opencode.setup({
      cmd = { "bunx", "opencode" },
      args = { "--standalone" },
      window = { layout = "below", size = 24 },
      keymaps = { toggle = "<leader>ox" },
      session = { continue = true },
    })
    test.deep_equal({ "bunx", "opencode" }, config.cmd)
    test.deep_equal({ "--standalone" }, config.args)
    test.equal("below", config.window.layout)
    test.equal(24, config.window.size)
    test.equal("<leader>ox", config.keymaps.toggle)
    test.equal("<leader>os", config.keymaps.send_selection)
    test.equal(true, config.session.continue)
    pcall(opencode.stop)
  end)

  test.it("allows false to disable global keymaps", function()
    local opencode = fresh()
    opencode.setup({ keymaps = { toggle = false, send_selection = false } })
    local config = opencode.get_config()
    test.equal(false, config.keymaps.toggle)
    test.equal(false, config.keymaps.send_selection)
    test.equal("<leader>oq", config.keymaps.question_selection)
    pcall(opencode.stop)
  end)

  test.it("is repeatable and replaces the previous runtime", function()
    local opencode = fresh()
    opencode.setup({ window = { size = 50 } })
    opencode.setup({ window = { size = 70 } })
    test.equal(70, opencode.get_config().window.size)
    pcall(opencode.stop)
  end)

  test.it("rejects invalid terminal and session options", function()
    local opencode = fresh()
    test.error_matches("cmd", function()
      opencode.setup({ cmd = {} })
    end)
    test.error_matches("window.layout", function()
      opencode.setup({ window = { layout = "float" } })
    end)
    test.error_matches("remember_width", function()
      opencode.setup({ window = { remember_width = "yes" } })
    end)
    test.error_matches("session.continue", function()
      opencode.setup({ session = { continue = "yes" } })
    end)
    test.error_matches("keymaps.toggle", function()
      opencode.setup({ keymaps = { toggle = 42 } })
    end)
    test.error_matches("paste.ready_delay", function()
      opencode.setup({ paste = { ready_delay = -1 } })
    end)
  end)
end)
